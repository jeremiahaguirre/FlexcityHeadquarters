/** Whether the screen is in French (the app sets <html lang>). */
export function screenIsFrench(): boolean {
  return typeof document !== 'undefined' && document.documentElement.lang.toLowerCase().startsWith('fr');
}

/** A recorded answer with its sample text in French. Only whole strings are replaced. */
export function inFrench<T>(value: T): T {
  if (typeof value === 'string') return (DEMO_FRENCH[value] ?? value) as T;
  if (Array.isArray(value)) return value.map((v) => inFrench(v)) as T;
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, inFrench(v)])) as T;
  return value;
}
